#!/usr/bin/env node
// Looks up every character in js/characters.js on AniList and writes their
// image URLs to js/images.js.
//
//   node tools/fetch-images.js              # update js/images.js with URLs
//   node tools/fetch-images.js --download   # also save the files to images/ (git-ignored)
//   node tools/fetch-images.js --only gojo,ayanokoji
//   node tools/fetch-images.js --force      # re-look-up characters that already have a URL
//
// The game loads the URLs at runtime, so the images never need to be committed.

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const args = process.argv.slice(2);
const DOWNLOAD = args.includes("--download");
const FORCE = args.includes("--force");
const onlyIdx = args.indexOf("--only");
const ONLY = onlyIdx >= 0 ? new Set(args[onlyIdx + 1].split(",")) : null;

function loadScript(file) {
  const ctx = { window: {} };
  vm.createContext(ctx);
  if (fs.existsSync(file)) vm.runInContext(fs.readFileSync(file, "utf8"), ctx);
  return ctx.window;
}

const { CHARACTERS } = loadScript(path.join(ROOT, "js/characters.js"));
const imagesFile = path.join(ROOT, "js/images.js");
const existing = loadScript(imagesFile).CHARACTER_IMAGES || {};

const QUERY = `query ($search: String) {
  Page(perPage: 10) {
    characters(search: $search, sort: [SEARCH_MATCH]) {
      name { full }
      favourites
      image { large }
      media(perPage: 25) { nodes { title { romaji english } synonyms } }
    }
  }
}`;

const norm = (s) => (s || "").toLowerCase().replace(/[^a-z0-9]/g, "");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function anilist(search) {
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch("https://graphql.anilist.co", {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify({ query: QUERY, variables: { search } }),
    });
    if (res.status === 429) {
      const wait = Number(res.headers.get("retry-after") || 60);
      console.log(`  rate limited, waiting ${wait}s`);
      await sleep(wait * 1000);
      continue;
    }
    if (!res.ok) throw new Error(`AniList HTTP ${res.status}`);
    return (await res.json()).data.Page.characters;
  }
  throw new Error("AniList kept rate limiting");
}

// Pick the result that appears in the right series (falls back to the top hit).
function choose(results, series) {
  const want = norm(series).replace(/super$/, ""); // "Dragon Ball Super" also matches "Dragon Ball Z"
  const inSeries = results.filter((r) =>
    r.media.nodes.some((m) =>
      [m.title.romaji, m.title.english, ...(m.synonyms || [])].some((t) => norm(t).includes(want))
    )
  );
  const pool = inSeries.length ? inSeries : results;
  return { pick: pool[0], matchedSeries: inSeries.length > 0 };
}

async function main() {
  const out = { ...existing };
  if (DOWNLOAD) fs.mkdirSync(path.join(ROOT, "images"), { recursive: true });

  for (const c of CHARACTERS) {
    if (ONLY && !ONLY.has(c.id)) continue;
    if (out[c.id] && !FORCE && !DOWNLOAD) continue;

    if (!out[c.id] || FORCE) {
      const results = await anilist(c.search || c.name);
      if (!results.length) { console.log(`✗ ${c.id}: no AniList results for "${c.search || c.name}"`); continue; }
      const { pick, matchedSeries } = choose(results, c.series);
      out[c.id] = pick.image.large;
      console.log(`${matchedSeries ? "✓" : "?"} ${c.id} -> ${pick.name.full}${matchedSeries ? "" : "  (series not confirmed, check this one)"}`);
      await sleep(700); // stay well under AniList's rate limit
    }

    if (DOWNLOAD && out[c.id]) {
      const ext = path.extname(new URL(out[c.id]).pathname) || ".jpg";
      const dest = path.join(ROOT, "images", c.id + ext);
      if (!fs.existsSync(dest)) {
        const res = await fetch(out[c.id]);
        if (res.ok) fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
        console.log(`  saved images/${c.id}${ext}`);
      }
    }
  }

  const body = Object.keys(out).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join("\n");
  fs.writeFileSync(
    imagesFile,
    `// Generated by tools/fetch-images.js. Character id -> image URL (AniList).\n` +
      `// Edit a URL by hand to swap an image; re-run the script with --force to look it up again.\n` +
      `window.CHARACTER_IMAGES = {\n${body}\n};\n`
  );
  console.log(`\nWrote ${Object.keys(out).length} image URLs to js/images.js`);
}

main().catch((e) => { console.error(e); process.exit(1); });
